export const strings = { en, 'zh-TW': zhTW };
export function t(key: TextKey, values: Record<string, string | number> = {}, locale: Language = language.current): string {
  // English counts use {name|one|other}: the singular form when the value is exactly 1.
  return strings[locale][key]
    .replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (_, name: string, one: string, other: string) => Number(values[name]) === 1 ? one : other)
    .replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}
export function materialName(index: number, locale: Language = language.current) { return t(`material${index}` as TextKey, {}, locale); }
export function cardName(id: EventCardId, locale: Language = language.current) { return t(`card.${id}`, {}, locale); }
/** Read-only localized projection of a draw. No game state or saved effect strings are changed. */
export function cardText(card: Pick<DrawnCard, 'id' | 'material' | 'targetBallId'>, locale: Language = language.current) {
  const value = C.board.events, tr = (key: TextKey, args = {}) => t(key, args, locale);
  const target = card.targetBallId === undefined ? tr('nextTarget') : tr('ballTarget', { id: card.targetBallId });
  let effect: string;
  switch (card.id) {
    case 'extra-shot': effect = tr('effect.extra-shot', { n: value.bonusShots }); break;
    case 'change-material': effect = tr('effect.change-material', { material: materialName(card.material ?? 0, locale) }); break;
    case 'rewind': effect = tr('effect.rewind', { n: value.rewind }); break;
    case 'double-burst': effect = tr('effect.double-burst', { target, n: value.burstMultiplier }); break;
    case 'burst-now': effect = card.targetBallId === undefined ? tr('effect.burst-empty') : tr('effect.burst-now', { id: card.targetBallId }); break;
    case 'chip-boss': effect = tr('effect.chip-boss', { n: value.bossDamage }); break;
  }
  return { name: cardName(card.id, locale), effect };
}
